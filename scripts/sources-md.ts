/**
 * Render numbered sources into Markdown:
 *
 *   pnpm tsx scripts/sources-md.ts <topic-slug>        # data/sources.json -> data/SOURCES.md
 *   pnpm tsx scripts/sources-md.ts --shared fitness    # shared/fitness/sources.json -> shared/fitness/SOURCES.md
 *
 * Reads `src/content/topics/<slug>/data/sources.json` (validated with the
 * shared schema, src/content/schema/sources.ts) and writes one line per
 * source, `- [S1] English text / 中文 — https://…`, plus the note when there
 * is one. Only the block between the two marker comments is replaced, so the
 * rest of SOURCES.md (map data provenance, licences, registration notes) is
 * kept; without markers the block is appended. A topic that uses shared
 * fitness data (`data/training.json`) also gets the shared `M#` list in its
 * own marked block. Exit 1 on invalid input.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sharedSourcesFile, sourcesFile, type SourceEntry } from '../src/content/schema/sources';
import { formatIssues } from '../src/engines/schemas';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TOPICS_DIR = process.env.ATLAS_TOPICS_DIR ? resolve(process.env.ATLAS_TOPICS_DIR) : join(ROOT, 'src/content/topics');
const SHARED_DIR = process.env.ATLAS_SHARED_DIR ? resolve(process.env.ATLAS_SHARED_DIR) : join(ROOT, 'src/content/shared');

export const BEGIN = '<!-- sources:begin (generated by scripts/sources-md.ts from sources.json; edit sources.json) -->';
export const END = '<!-- sources:end -->';
/** Markers of the shared-source block in a topic's SOURCES.md. */
export const SHARED_BEGIN = '<!-- shared-sources:begin (generated by scripts/sources-md.ts from src/content/shared/fitness/sources.json) -->';
export const SHARED_END = '<!-- shared-sources:end -->';

/** One Markdown list line per source. */
export function sourceLine(s: SourceEntry): string {
  const text = s.text.zh ? `${s.text.en} / ${s.text.zh}` : s.text.en;
  const note = s.note ? ` (${s.note.zh ? `${s.note.en} / ${s.note.zh}` : s.note.en})` : '';
  return `- [${s.id}] ${text}${note}${s.design ? ' (design study / 设计研究)' : ''}${s.url ? ` — ${s.url}` : ''}`;
}

/** The generated block, markers included. */
export function sourcesBlock(sources: readonly SourceEntry[], markers: readonly [string, string] = [BEGIN, END]): string {
  return [markers[0], ...sources.map(sourceLine), markers[1]].join('\n');
}

/** `existing` with its generated block replaced (or a new file / appended block under `heading`). */
export function mergeSourcesMd(existing: string | null, block: string, topic: string, markers: readonly [string, string] = [BEGIN, END], heading = 'Numbered sources'): string {
  if (existing === null) return `# Sources · ${topic}\n\n${block}\n`;
  const start = existing.indexOf(markers[0]);
  const end = existing.indexOf(markers[1]);
  if (start >= 0 && end > start) return existing.slice(0, start) + block + existing.slice(end + markers[1].length);
  return `${existing.replace(/\s*$/, '')}\n\n## ${heading}\n\n${block}\n`;
}

/** The shared sources of an area (`fitness`), validated; null with a message on stderr when unreadable. */
function readShared(area: string): SourceEntry[] | null {
  const input = join(SHARED_DIR, area, 'sources.json');
  if (!existsSync(input)) {
    console.error(`sources-md: ${relative(ROOT, input)} not found`);
    return null;
  }
  const parsed = sharedSourcesFile.safeParse(JSON.parse(readFileSync(input, 'utf8')));
  if (!parsed.success) {
    console.error(`sources-md: invalid ${relative(ROOT, input)}\n  ${formatIssues(parsed.error).join('\n  ')}`);
    return null;
  }
  return parsed.data.sources;
}

function main(): void {
  const slug = process.argv[2];
  if (!slug) {
    console.error('usage: pnpm tsx scripts/sources-md.ts <topic-slug> | --shared <area>');
    process.exitCode = 1;
    return;
  }
  if (slug === '--shared') {
    const area = process.argv[3] ?? 'fitness';
    const shared = readShared(area);
    if (!shared) {
      process.exitCode = 1;
      return;
    }
    const output = join(SHARED_DIR, area, 'SOURCES.md');
    const existing = existsSync(output) ? readFileSync(output, 'utf8') : null;
    writeFileSync(output, mergeSourcesMd(existing, sourcesBlock(shared), `shared/${area}`));
    console.log(`sources-md: ${shared.length} shared source(s) -> ${relative(ROOT, output)}`);
    return;
  }
  const dataDir = join(TOPICS_DIR, slug, 'data');
  const input = join(dataDir, 'sources.json');
  if (!existsSync(input)) {
    console.error(`sources-md: ${relative(ROOT, input)} not found`);
    process.exitCode = 1;
    return;
  }
  const parsed = sourcesFile.safeParse(JSON.parse(readFileSync(input, 'utf8')));
  if (!parsed.success) {
    console.error(`sources-md: invalid ${relative(ROOT, input)}\n  ${formatIssues(parsed.error).join('\n  ')}`);
    process.exitCode = 1;
    return;
  }
  const output = join(dataDir, 'SOURCES.md');
  const existing = existsSync(output) ? readFileSync(output, 'utf8') : null;
  let md = mergeSourcesMd(existing, sourcesBlock(parsed.data.sources), slug);
  // A topic on shared fitness data lists the shared M# sources it can cite too.
  if (existsSync(join(dataDir, 'training.json'))) {
    const shared = readShared('fitness');
    if (!shared) {
      process.exitCode = 1;
      return;
    }
    md = mergeSourcesMd(md, sourcesBlock(shared, [SHARED_BEGIN, SHARED_END]), slug, [SHARED_BEGIN, SHARED_END], 'Shared sources (M#)');
    console.log(`sources-md: ${shared.length} shared source(s) -> ${relative(ROOT, output)}`);
  }
  writeFileSync(output, md);
  console.log(`sources-md: ${parsed.data.sources.length} source(s) -> ${relative(ROOT, output)}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
