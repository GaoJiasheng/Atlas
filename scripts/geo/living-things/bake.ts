import type { Model, V3 } from './kit';
const palette:Record<string,string>={eye:'#24251f',feathers:'#d7d0bb',tissue:'#d6c7ae',chitin:'#665e4e',wood:'#8b6946',fabric:'#93846a',scales:'#9b956d',enamel:'#e8e4da',plastic:'#b7b09d',abrasive:'#9a9484',glass:'#b1c3b9',rubber:'#282a27'};
const tokenPalette:Record<string,string>={'token:ink-2':'#555047','token:bone':'#d8cdb1','token:food':'#81934a'};
export function modelGeometry(model:Model):BufferGeometry {
 const positions:number[]=[],normals:number[]=[],colors:number[]=[],indices:number[]=[];
 for(const prim of [model.primitive,...model.extra]){
  const pieces=prim.kind==='__mesh'?[{geometry:prim.geometry as BufferGeometry,matrices:null}]:partPieces({primitive:primitiveSchema.parse(prim)});
  for(const piece of pieces){
   if('lines'in piece&&piece.lines){piece.geometry.dispose();continue;}
   for(const mat of piece.matrices??[new Matrix4()]){
    const g=piece.geometry.clone().applyMatrix4(mat).translate(...prim.at),p=g.getAttribute('position'),n=g.getAttribute('normal'),c=g.getAttribute('color');
    const ref=(prim.tint??palette[String(prim.color)]??prim.color??'#8a8378') as string,col=new Color(tokenPalette[ref]??ref);
    const copies=g.userData.twoSided?2:1;
    for(let side=0;side<copies;side++){
     const off=positions.length/3;
     for(let i=0;i<p.count;i++){
      positions.push(p.getX(i),p.getY(i),p.getZ(i));
      normals.push(n.getX(i)*(side?-1:1),n.getY(i)*(side?-1:1),n.getZ(i)*(side?-1:1));
      colors.push(c?c.getX(i):col.r,c?c.getY(i):col.g,c?c.getZ(i):col.b);
     }
     const count=g.index?.count??p.count;
     for(let i=0;i<count;i+=3){const a=g.index?.getX(i)??i,b=g.index?.getX(i+1)??i+1,d=g.index?.getX(i+2)??i+2;indices.push(off+a,off+(side?d:b),off+(side?b:d));}
    }
    g.dispose();
   }
   if(prim.kind!=='__mesh')piece.geometry.dispose();
  }
 }
 const g=new BufferGeometry();g.setAttribute('position',new Float32BufferAttribute(positions,3));g.setAttribute('normal',new Float32BufferAttribute(normals,3));g.setAttribute('color',new Float32BufferAttribute(colors,3));g.setAttribute('uv',new Float32BufferAttribute(new Float32Array(positions.length/3*2),2));g.setIndex(indices);g.computeBoundingBox();return g;
}
export function modelBounds(model:Model):{min:V3;max:V3}{
 const box=new Box3();
 for(const prim of [model.primitive,...model.extra]){
  if(prim.kind==='__mesh'){
   const g=prim.geometry as BufferGeometry;g.computeBoundingBox();box.union(g.boundingBox!.clone().translate(new Vector3(...prim.at)));
  }else{
   for(const p of partPieces({primitive:primitiveSchema.parse(prim)})){
    if(p.lines){p.geometry.dispose();continue;}p.geometry.computeBoundingBox();
    for(const m of p.matrices??[new Matrix4()])box.union(p.geometry.boundingBox!.clone().applyMatrix4(m).translate(new Vector3(...prim.at)));
    p.geometry.dispose();
   }
  }
 }
 return {min:box.min.toArray() as V3,max:box.max.toArray() as V3};
}
export interface BakedSpecimen {id:string;geometry:BufferGeometry;at:V3}
export async function writeSculptures(path:string,specimens:BakedSpecimen[]):Promise<void>{
 const doc=new Document(),buffer=doc.createBuffer(),scene=doc.createScene('living-things');
 doc.getRoot().getAsset().copyright='Copyright (c) 2026 Gao Jiasheng / Atlas (atlas.gavin.pub). Original procedural specimen sculptures generated by scripts/geo/living-things/ and the opt-in bird sculpture API; MIT License (repository LICENSE). No third-party meshes, scans or photograph textures.';
 const floors=new Map<string,number>();
 const material=doc.createMaterial('original-sculpture').setBaseColorFactor([1,1,1,1]).setRoughnessFactor(.8).setMetallicFactor(0);
 for(const {id,geometry:g,at}of specimens){
  g.computeBoundingBox();floors.set(id,g.boundingBox!.min.y);
  const primitive=doc.createPrimitive().setMaterial(material);
  for(const [attribute,semantic,type]of [['position','POSITION','VEC3'],['normal','NORMAL','VEC3'],['color','COLOR_0','VEC3']]as const){
   const a=g.getAttribute(attribute),array=new Float32Array(a.array);primitive.setAttribute(semantic,doc.createAccessor().setType(type).setArray(array).setBuffer(buffer));
  }
  primitive.setIndices(doc.createAccessor().setType('SCALAR').setArray(new Uint32Array(g.index!.array)).setBuffer(buffer));
  const node=doc.createNode(id).setMesh(doc.createMesh(id).addPrimitive(primitive)).setTranslation(at).setExtras({closed:true});scene.addChild(node);
 }
 await Promise.all([MeshoptEncoder.ready,MeshoptDecoder.ready,MeshoptSimplifier.ready]);
 // Preserve open anatomical borders; the error cap is a fraction of each
 // specimen's radius. Filtered normals reduce payload without faceting.
 await doc.transform(weld(),simplify({simplifier:MeshoptSimplifier,ratio:.5,error:.0004,lockBorder:true}));
 // Edge collapse can remove the lowest sample. Reseat the simplified surface
 // on its original cell floor so sorting never introduces a visible hover.
 for(const node of scene.listChildren()){
  const p=node.getMesh()!.listPrimitives()[0]!.getAttribute('POSITION')!,a=p.getArray()!;
  let low=Infinity;for(let i=1;i<a.length;i+=3)low=Math.min(low,a[i]!);
  const dy=floors.get(node.getName())!-low;
  for(let i=1;i<a.length;i+=3)a[i]=a[i]!+dy;
 }
 await doc.transform(meshopt({encoder:MeshoptEncoder,level:'high',quantizePosition:15,quantizeNormal:8,quantizeColor:8}));
 const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.encoder':MeshoptEncoder,'meshopt.decoder':MeshoptDecoder});
 const binary=await io.writeBinary(doc);
 if(binary.byteLength>1_500_000)throw new Error(`living-things.glb exceeds 1.5 MB: ${binary.byteLength} bytes`);
 writeFileSync(path,binary);
}
